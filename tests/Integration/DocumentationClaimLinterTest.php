<?php

declare(strict_types=1);

namespace Semitexa\Docs\Tests\Integration;

use PHPUnit\Framework\Attributes\Test;
use PHPUnit\Framework\TestCase;
use Semitexa\Docs\Application\Service\DocumentationClaimLinter;
use Semitexa\Docs\Tests\Support\UnreadableFileStream;

/**
 * The linter's value is entirely in being believed, so the tests that matter are
 * the ones about *not* reporting: every false positive here was found in the
 * real corpus first, and each would have made the report easy to dismiss.
 */
final class DocumentationClaimLinterTest extends TestCase
{
    private string $dir;

    protected function setUp(): void
    {
        $this->dir = sys_get_temp_dir() . '/docs-lint-' . bin2hex(random_bytes(4));
        mkdir($this->dir);
    }

    protected function tearDown(): void
    {
        foreach (glob($this->dir . '/*') ?: [] as $file) {
            unlink($file);
        }

        rmdir($this->dir);
    }

    #[Test]
    public function reports_an_attribute_and_a_command_that_do_not_exist(): void
    {
        $findings = $this->lint("Use `#[AsInvented]` then run `bin/semitexa nope:missing`.\n");

        self::assertSame(
            [['attribute', 'AsInvented'], ['command', 'nope:missing']],
            array_map(static fn (array $f): array => [$f['kind'], $f['claim']], $findings),
        );
    }

    #[Test]
    public function published_pages_must_declare_the_release_they_were_verified_against(): void
    {
        $findings = $this->lint(<<<'MD'
---
status: published
---
# Page
MD);

        self::assertSame([['release_metadata', 'verified_against']], array_map(
            static fn (array $finding): array => [$finding['kind'], $finding['claim']],
            $findings,
        ));
    }

    #[Test]
    public function a_quoted_status_is_the_same_page_as_an_unquoted_one(): void
    {
        // DocumentFrontMatterParser unquotes scalars, so both spellings load
        // as `published`. A gate that only matched one silently exempted the
        // other from the release check.
        foreach (['"published"', "'canonical'"] as $status) {
            $findings = $this->lint("---\nstatus: {$status}\n---\n# Page\n");

            self::assertSame([['release_metadata', 'verified_against']], array_map(
                static fn (array $finding): array => [$finding['kind'], $finding['claim']],
                $findings,
            ), $status . ' must still be checked for provenance.');
        }
    }

    #[Test]
    public function an_exempt_page_is_exempt_from_release_provenance_too(): void
    {
        // `docs:reference:generate` writes `verified_against: unverified` when
        // it cannot resolve a release. Generated reference is verified by
        // `docs:reference:generate --check`, so claim linting must not fail it.
        self::assertSame([], $this->lint(<<<'MD'
---
status: published
verified_against: unverified
---
<!-- Generated by `bin/semitexa docs:reference:generate` -->
# Page
MD));

        self::assertSame([], $this->lint(<<<'MD'
---
status: published
---
<!-- docs-lint-ignore-file -->
# Page
MD));
    }

    #[Test]
    public function a_page_cannot_claim_verification_against_a_future_release(): void
    {
        $findings = $this->lint(<<<'MD'
---
status: canonical
verified_against: 2026.09.20.1200
---
# Page
MD);

        self::assertSame('release_version', $findings[0]['kind']);
        self::assertSame('2026.09.19.1020', $findings[0]['suggestion']);
    }

    #[Test]
    public function checks_inside_fenced_blocks_because_that_is_what_readers_copy(): void
    {
        $findings = $this->lint("Example:\n\n```php\n#[AsInvented]\nfinal class Thing {}\n```\n");

        self::assertCount(1, $findings);
        self::assertSame(4, $findings[0]['line'], 'The line reported must be the one inside the block.');
    }

    #[Test]
    public function an_attribute_from_another_library_is_not_an_invention(): void
    {
        // PHPUnit's own attributes appear in testing pages. Flagging them made
        // 3 of the first 35 findings noise.
        self::assertSame([], $this->lint("Mark it `#[RunTestsInSeparateProcesses]`.\n"));
    }

    #[Test]
    public function a_documentation_filename_is_not_an_environment_variable(): void
    {
        // A bare-token env regex counted MODULE_STRUCTURE and ADDING_ROUTES as
        // unknown keys and put the false-positive rate at 82%.
        self::assertSame([], $this->lint("See MODULE_STRUCTURE and ADDING_ROUTES for detail.\n"));
    }

    #[Test]
    public function a_key_the_code_composes_at_runtime_is_accepted(): void
    {
        // TENANT_ACME_DOMAIN is never written down anywhere: the code builds
        // "TENANT_{$id}_DOMAIN", so only the shape can be known.
        self::assertSame([], $this->lint("TENANT_ACME_DOMAIN=acme.test\n"));
    }

    #[Test]
    public function a_rename_is_reported_with_the_name_that_replaced_it(): void
    {
        $findings = $this->lint("Declare `#[SatisfiesServiceContrac]` on the class.\n");

        self::assertCount(1, $findings);
        self::assertSame('SatisfiesServiceContract', $findings[0]['suggestion']);
    }

    #[Test]
    public function a_before_section_may_name_the_api_being_migrated_from(): void
    {
        // A migration guide's whole job is to show what you are moving away
        // from. Reporting it would mean one can never be written.
        self::assertSame([], $this->lint(
            "## Access\n\n### Before\n\n```php\n#[AsInvented]\n```\n",
        ));
    }

    #[Test]
    public function the_after_section_of_the_same_page_is_still_checked(): void
    {
        $findings = $this->lint(
            "### Before\n\n`#[AsInvented]`\n\n### After\n\n`#[AlsoInvented]`\n",
        );

        self::assertSame(['AlsoInvented'], array_column($findings, 'claim'));
    }

    #[Test]
    public function a_wildcard_stands_for_the_attributes_it_covers(): void
    {
        // `#[InjectAs*]` is one claim about three attributes, not a claim about
        // an attribute called "InjectAs".
        self::assertSame([], $this->lint("Annotate with `#[AsPublic*]` properties.\n"));
    }

    #[Test]
    public function a_wildcard_matching_nothing_is_still_reported(): void
    {
        self::assertSame(['AsNothing*'], array_column($this->lint("Use `#[AsNothing*]`.\n"), 'claim'));
    }

    #[Test]
    public function the_ignore_marker_covers_the_line_below_it(): void
    {
        self::assertSame([], $this->lint(
            "<!-- docs-lint-ignore -->\nDon't create `#[AsInvented]` — identity comes from composer.json.\n",
        ));
    }

    #[Test]
    public function the_ignore_marker_above_a_block_covers_the_whole_block(): void
    {
        // A migration step that greps for retired names is one instruction, not
        // one finding per line.
        self::assertSame([], $this->lint(
            "<!-- docs-lint-ignore -->\n```bash\ngrep -r '#[AsInvented]' src\ngrep -r '#[AlsoInvented]' src\n```\n",
        ));
    }

    #[Test]
    public function a_whole_document_can_be_exempted(): void
    {
        // A proposal names unbuilt API in every other paragraph; marking each
        // line would bury the document in scaffolding.
        self::assertSame([], $this->lint(
            "<!-- docs-lint-ignore-file -->\n# Proposal\n\n`#[AsInvented]` and `#[AlsoInvented]` and `bin/semitexa nope:missing`.\n",
        ));
    }

    #[Test]
    public function generated_reference_is_owned_by_the_generator_check(): void
    {
        // A consumer may publish reference for optional packages it does not
        // install. Freshness belongs to docs:reference:generate --check;
        // docs:lint remains responsible for claims in hand-written prose.
        self::assertSame([], $this->lint(
            "<!-- Generated by `bin/semitexa docs:reference:generate` — do not edit by hand. -->\n"
            . "\nRun `bin/semitexa optional:missing`.\n",
        ));
    }

    #[Test]
    public function the_file_exemption_does_not_leak_to_other_documents(): void
    {
        file_put_contents($this->dir . '/exempt.md', "<!-- docs-lint-ignore-file -->\n`#[AsInvented]`\n");

        self::assertSame(['AlsoInvented'], array_column($this->lint("`#[AlsoInvented]`\n"), 'claim'));
    }

    #[Test]
    public function a_baseline_survives_the_corpus_moving_between_layouts(): void
    {
        // The same page is under packages/ in the monorepo and vendor/ in a
        // consumer project. A baseline keyed on the project path stops matching
        // when the corpus is read from the other one, and comes back reporting
        // everything it was recorded to hold.
        $linter = new DocumentationClaimLinter();
        $finding = ['kind' => 'attribute', 'claim' => 'AsInvented'];

        self::assertSame(
            $linter->fingerprint($finding + ['file' => '/app/packages/semitexa-docs/docs/en/routing/basic.md']),
            $linter->fingerprint($finding + ['file' => '/app/vendor/semitexa/docs/docs/en/routing/basic.md']),
        );
    }

    #[Test]
    public function a_baseline_written_before_the_root_was_stripped_still_matches(): void
    {
        // Recorded for /app/docs/guide.md by the previous linter: key @guide.md.
        $linter = new DocumentationClaimLinter();
        $finding = ['kind' => 'attribute', 'claim' => 'AsInvented', 'file' => '/app/docs/guide.md'];
        $oldBaseline = ['attribute:AsInvented@guide.md'];

        self::assertSame('attribute:AsInvented@docs/guide.md', $linter->fingerprint($finding, '/app'));
        self::assertSame(['attribute:AsInvented@docs/guide.md', 'attribute:AsInvented@guide.md'], $linter->baselineKeys($finding, '/app'));
        self::assertNotSame([], array_intersect($linter->baselineKeys($finding, '/app'), $oldBaseline));

        // The same page named relatively, as --path=docs/guide.md, still meets that old entry.
        $relative = ['file' => 'docs/guide.md'] + $finding;
        self::assertSame(['attribute:AsInvented@docs/guide.md', 'attribute:AsInvented@guide.md'], $linter->baselineKeys($relative, '/app'));
    }

    #[Test]
    public function only_a_baseline_from_before_rooted_keys_answers_to_old_spellings(): void
    {
        $linter = new DocumentationClaimLinter();
        $inDocs = ['kind' => 'attribute', 'claim' => 'AsInvented', 'file' => '/app/docs/guide.md'];
        // A new baseline entry for /app/guide.md is `@guide.md`, the old spelling of /app/docs/guide.md.
        $entry = [$linter->fingerprint(['kind' => 'attribute', 'claim' => 'AsInvented', 'file' => '/app/guide.md'], '/app')];

        self::assertSame(['attribute:AsInvented@guide.md'], $entry);
        self::assertFalse($linter->matchesBaseline($inDocs, '/app', $entry, legacyBaseline: false), 'a new baseline does not hide another page');
        self::assertTrue($linter->matchesBaseline($inDocs, '/app', $entry, legacyBaseline: true), 'an old one still holds what it recorded');
        self::assertTrue($linter->matchesBaseline($inDocs, '/app', ['attribute:AsInvented@docs/guide.md'], legacyBaseline: false));
    }

    #[Test]
    public function two_project_pages_never_share_a_new_key(): void
    {
        $linter = new DocumentationClaimLinter();
        $finding = ['kind' => 'attribute', 'claim' => 'AsInvented'];
        $key = static fn (string $file): string => $linter->fingerprint($finding + ['file' => $file], '/app');

        self::assertSame('attribute:AsInvented@guide.md', $key('/app/guide.md'));
        self::assertSame('attribute:AsInvented@src/modules/M/docs/guide.md', $key('/app/src/modules/M/docs/guide.md'));
        self::assertSame('attribute:AsInvented@semitexa-docs/en/x.md', $key('/app/vendor/semitexa/docs/docs/en/x.md'));
        self::assertSame('attribute:AsInvented@en/x.md', $key('/app/en/x.md'), 'a project page at en/x.md is not the corpus page');
    }

    #[Test]
    public function an_old_baseline_written_with_dot_slash_still_matches_a_page_outside_docs(): void
    {
        // The old code kept ./README.md as @./README.md (no docs/ to cut at).
        $linter = new DocumentationClaimLinter();
        $finding = ['kind' => 'attribute', 'claim' => 'AsInvented'];

        foreach (['/app/README.md', 'README.md', './README.md'] as $named) {
            self::assertTrue($linter->matchesBaseline($finding + ['file' => $named], '/app', ['attribute:AsInvented@./README.md'], legacyBaseline: true), $named);
        }
    }

    #[Test]
    public function a_dot_slash_names_the_same_page(): void
    {
        $linter = new DocumentationClaimLinter();
        $finding = ['kind' => 'attribute', 'claim' => 'AsInvented'];

        self::assertSame(
            $linter->fingerprint($finding + ['file' => '/app/docs/guide.md'], '/app'),
            $linter->fingerprint($finding + ['file' => './docs/guide.md'], '/app'),
        );
        self::assertContains('attribute:AsInvented@guide.md', $linter->baselineKeys($finding + ['file' => './docs/guide.md'], '/app'));
    }

    #[Test]
    public function a_project_page_is_one_key_whether_named_relative_or_absolute(): void
    {
        // ai:verify names a changed page absolutely (/app/docs/guide.md); a
        // person writing a baseline types --path=docs/guide.md. Read one way, a
        // baseline written the other way reported its accepted findings as new.
        $linter = new DocumentationClaimLinter();
        $finding = ['kind' => 'attribute', 'claim' => 'AsInvented'];

        foreach (['docs/guide.md', 'client/ubuntu/README.md'] as $page) {
            self::assertSame(
                $linter->fingerprint($finding + ['file' => $page], '/app'),
                $linter->fingerprint($finding + ['file' => '/app/' . $page], '/app'),
                $page,
            );
        }
        // A corpus page is one key under packages/ and vendor/, and an existing
        // baseline still finds it under the key it was written with.
        foreach (['/app/vendor/semitexa/docs/docs/en/routing/basic.md', '/app/packages/semitexa-docs/docs/en/routing/basic.md'] as $corpus) {
            self::assertSame('attribute:AsInvented@semitexa-docs/en/routing/basic.md', $linter->fingerprint($finding + ['file' => $corpus], '/app'));
            self::assertTrue($linter->matchesBaseline($finding + ['file' => $corpus], '/app', ['attribute:AsInvented@en/routing/basic.md'], legacyBaseline: true));
        }
    }

    /**
     * @return list<array<string, mixed>>
     */
    #[Test]
    public function an_unreadable_page_fails_the_gate_instead_of_passing_it(): void
    {
        self::assertTrue(stream_wrapper_register('unreadable', UnreadableFileStream::class));

        try {
            $this->expectException(\RuntimeException::class);
            $this->expectExceptionMessageMatches('/Cannot read documentation file/');
            (new DocumentationClaimLinter())->lint($this->index(), ['unreadable://page.md']);
        } finally {
            stream_wrapper_unregister('unreadable');
        }
    }

    private function lint(string $markdown): array
    {
        file_put_contents($this->dir . '/page.md', $markdown);

        $report = (new DocumentationClaimLinter())->lint($this->index(), [$this->dir]);

        /** @var list<array<string, mixed>> $findings */
        $findings = $report['findings'];

        return $findings;
    }

    /**
     * @return array<string, mixed>
     */
    private function index(): array
    {
        return [
            'attributes' => [
                ['name' => 'AsPublicPayload'],
                ['name' => 'SatisfiesServiceContract'],
            ],
            'foreign_attributes' => ['RunTestsInSeparateProcesses'],
            'commands' => [['name' => 'ai:verify'], ['name' => 'docs:lint']],
            'env_keys' => ['SWOOLE_PORT'],
            'env_key_patterns' => ['TENANT_*_DOMAIN'],
            'release_version' => '2026.09.19.1020',
        ];
    }
}
